import { randomBytes, randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import { resolve } from 'node:path';
import { MongoClient } from 'mongodb';
import { adminPermissions } from '../services/auth/dist/router.js';
import { hashAdminPassword } from '../services/auth/dist/admin-password.js';

try {
  process.loadEnvFile('.env');
} catch {
  /* Local defaults only. */
}
const uri =
  process.env.MONGO_URI ?? 'mongodb://127.0.0.1:27017/?directConnection=true&replicaSet=rs0';
if (
  process.env.NODE_ENV === 'production' ||
  !/^mongodb:\/\/(?:127\.0\.0\.1|localhost)(?::|\/)/.test(uri)
)
  throw new Error('This helper only provisions the local development database');
const output = resolve('.local/admin-login.txt');
if (process.env.ADMIN_LOGIN_ID && process.env.ADMIN_PASSWORD_HASH) {
  console.log('Admin password login is already configured. Existing credentials were preserved.');
  console.log(`Private credential file, if generated by this helper: ${output}`);
  process.exit(0);
}
if (process.env.ADMIN_LOGIN_ID || process.env.ADMIN_PASSWORD_HASH)
  throw new Error('Partial admin configuration found; existing values were preserved');
let exists = false;
try {
  await access(output);
  exists = true;
} catch {
  /* Fresh setup. */
}
if (exists)
  throw new Error('An existing private credential file was preserved; reconcile it before setup');
const loginId = `admin-${randomBytes(5).toString('hex')}@cravecart.local`;
const password = randomBytes(24).toString('base64url');
const passwordHash = await hashAdminPassword(password);
const client = new MongoClient(uri);
try {
  await client.connect();
  const db = client.db(`${process.env.MONGO_DB_PREFIX ?? 'cravecart'}_auth`);
  await db.collection('users').createIndex({ contact: 1 }, { unique: true });
  await db.collection('users').insertOne({
    _id: randomUUID(),
    contact: loginId,
    name: 'Local administrator',
    status: 'ACTIVE',
    roles: ['customer', 'admin'],
    permissions: adminPermissions,
    createdAt: new Date(),
  });
  let env = '';
  try {
    env = await readFile('.env', 'utf8');
  } catch {
    /* Create the private file. */
  }
  function set(key, value) {
    const pattern = new RegExp(`^${key}=.*$`, 'm');
    env = pattern.test(env)
      ? env.replace(pattern, () => `${key}=${value}`)
      : `${env.trimEnd()}\n${key}=${value}\n`;
  }
  set('ADMIN_LOGIN_ID', loginId);
  set('ADMIN_PASSWORD_HASH', passwordHash);
  await mkdir(resolve('.local'), { recursive: true });
  await writeFile(
    output,
    `CraveCart local administrator\n\nURL: http://localhost:5173/admin/login\nAdmin login ID: ${loginId}\nPassword: ${password}\n\nOn first login, enroll your authenticator and save the recovery codes.\nKeep this file private. The server stores a salted scrypt hash, not this password.\n`,
    { flag: 'wx', mode: 0o600 },
  );
  await writeFile('.env', env, { mode: 0o600 });
  console.log('Local administrator created; credentials were not printed.');
  console.log(`Open the private credential file: ${output}`);
  console.log('Restart the development services to load the new server settings.');
} finally {
  await client.close();
}
